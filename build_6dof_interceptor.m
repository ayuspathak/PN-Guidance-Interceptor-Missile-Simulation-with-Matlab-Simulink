muxActBlk = [modelName '/Mux_Delta_Actual'];
add_block('simulink/Signal Routing/Mux', muxActBlk, ...
    'Position', [1010 380 1020 440], 'Inputs', '2');


%%  7) AERODYNAMICS -- forces & moments from state + fin deflection

aeroScript = sprintf([ ...
'function [F, M, alpha, beta, Vt] = fcn(x, delta)\n' ...
'%%#codegen\n' ...
'%% Generic linear missile aero model + boost/sustain thrust.\n' ...
'u=x(1); v=x(2); w=x(3); q=x(5); r=x(6);\n' ...
'zpos = x(12);\n\n' ...
'Vt = sqrt(u^2+v^2+w^2);\n' ...
'if Vt < 1\n' ...
'    Vt = 1;\n' ...
'end\n' ...
'alpha = atan2(w,u);\n' ...
'beta  = asin(max(min(v/Vt,1),-1));\n\n' ...
'%% simple exponential atmosphere\n' ...
'alt = -zpos;\n' ...
'rho0 = 1.225; H = 8500;\n' ...
'rho = rho0*exp(-alt/H);\n' ...
'qbar = 0.5*rho*Vt^2;\n\n' ...
'Sref = 0.0314;   %% m^2, reference area (~200mm diameter body)\n' ...
'd    = 0.2;      %% m, reference length\n\n' ...
'%% aero coefficients (generic, linear)\n' ...
'CNalpha = 12; CNdelta = 8;\n' ...
'CYbeta  = -12; CYdelta = -8;\n' ...
'Cmalpha = -4;  Cmdelta = -10; Cmq = -200;\n' ...
'Cnbeta  = 4;   Cndelta = 10;  Cnr = -200;\n' ...
'CA0 = 0.3;      %% axial drag coefficient\n\n' ...
'delta_p = delta(1); delta_y = delta(2);\n\n' ...
'CN = CNalpha*alpha + CNdelta*delta_p;\n' ...
'CY = CYbeta*beta   + CYdelta*delta_y;\n' ...
'CA = CA0;\n\n' ...
'Cm = Cmalpha*alpha + Cmdelta*delta_p + Cmq*q*d/(2*Vt);\n' ...
'Cn = Cnbeta*beta   + Cndelta*delta_y + Cnr*r*d/(2*Vt);\n' ...
'Cl = 0;   %% no roll control modeled\n\n' ...
'%% simple boost-sustain thrust profile (illustrative only)\n' ...
'thrust = 400;   %% N, constant sustain thrust along body x-axis\n\n' ...
'Fx = -qbar*Sref*CA + thrust;\n' ...
'Fy =  qbar*Sref*CY;\n' ...
'Fz = -qbar*Sref*CN;\n\n' ...
'Mx = qbar*Sref*d*Cl;\n' ...
'My = qbar*Sref*d*Cm;\n' ...
'Mz = qbar*Sref*d*Cn;\n\n' ...
'F = [Fx;Fy;Fz];\n' ...
'M = [Mx;My;Mz];\n' ...
'end']);

add_matlab_fcn_block(modelName, 'Aerodynamics', [280 260 420 340], aeroScript);


